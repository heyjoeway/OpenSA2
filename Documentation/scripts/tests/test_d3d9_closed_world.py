def test_live_play_logs_once_counts_every_call_and_answers_as_before(builds, tmp_path):
    fifo = tmp_path / "keys.fifo"
    os.mkfifo(fifo)
    code, rec, err = probe(builds, "trap", "unlisted", tmp_path, SA2_INPUT_DI_SOURCE=str(fifo))
    assert code == 0 and rec["failures"] == 0, rec.get("failed")
    assert rec["world_mode"] == "log"
    # The no-handler method and the unnamed slot still refuse by their old notes.
    assert rec["notes"] == [
        f"IDirect3DDevice9::GetPaletteEntries called from {RETADDR} on {DEVICE}: it writes through "
        "a pointer the guest then dereferences, and this runtime has no honest value to put there",
        f"IDirect3DDevice9 vtable slot 120 called from {RETADDR} on {DEVICE}: this runtime does not "
        "name that slot, and popping a guessed argument count would corrupt the caller's frame "
        "rather than answer wrongly"]
    loud = [line for line in err.splitlines() if line.startswith("*** d3d9 CLOSED WORLD: ")]
    assert [re.match(r"\*\*\* d3d9 CLOSED WORLD: (\S+) ", line).group(1) for line in loud] == [
        "IDirect3DDevice9::EvictManagedResources", "IDirect3DDevice9::SetGammaRamp",
        "IDirect3DDevice9::SetFVF", "IDirect3DDevice9::GetPaletteEntries"]
    assert "live play goes on and answers it as before" in loud[0]
    assert "live play stops here as before, since this runtime has no handler for it" in loud[3]
    assert err.endswith(
        "*** d3d9 CLOSED WORLD summary (live play): 5 method(s) off the M7 list called 8 time(s), "
        "each of which a gate or automated run would trap: IDirect3DDevice9::EvictManagedResources "
        "x2 first from 0x00401000 (answered); IDirect3DDevice9::SetGammaRamp x3 first from "
        "0x00401000 (answered); IDirect3DDevice9::SetFVF x1 first from 0x00401000 (answered); "
        "IDirect3DDevice9::GetPaletteEntries x1 first from 0x00401000 (refused); IDirect3DDevice9 "
        "slot 120 x1 first from 0x00401000 (unnamed-slot) ***\n")
    cw = rec["closed_world"]
    assert (cw["mode"], cw["live_keyboard_source"], cw["automated_session"], cw["listed_methods"],
            cw["unlisted_methods"], cw["unlisted_calls"]) == ("log", True, False, listed_n(), 5, 8)
    assert [(r["method"], r["slot"], r["calls"], r["first_seq"], r["outcome"]) for r in cw["unlisted"]] == [
        ("EvictManagedResources", 5, 2, 7, "answered"), ("SetGammaRamp", 21, 3, 9, "answered"),
        ("SetFVF", 89, 1, 12, "answered"), ("GetPaletteEntries", 72, 1, 13, "refused"),
        (None, 120, 1, 14, "unnamed-slot")]
    # Answered as before: the open build's answers, guest bytes and counters, call for call.
    code, opened, open_err = probe(builds, "open", "unlisted", tmp_path)
    assert code == 0 and open_err == ""
    assert rec["trace"] == opened["trace"] and rec["stats"] == opened["stats"]
    assert [(t["method"], t["eax"], t["popped"]) for t in rec["trace"]] == [
        ("EvictManagedResources", "0x00000000", 8), ("EvictManagedResources", "0x00000000", 8),
        ("SetGammaRamp", "0x00000000", 20), ("SetGammaRamp", "0x00000000", 20),
        ("SetGammaRamp", "0x00000000", 20), ("SetFVF", "0x00000000", 12)]
    assert opened["closed_world"]["mode"] == "open"
    assert [r["outcome"] for r in opened["closed_world"]["unlisted"]] == [
        "answered", "answered", "answered", "refused", "unnamed-slot"]


