#!/usr/bin/env python3
"""S2 wrap: build runtime v0 around the lifted IR and re-run the existing evidence through it.

Stage S2, design 5 (S2) "Runtime v0: guest memory, CPU state, function table,
`sa2_peek`/poke, direct call entry", decision 2026-09-19-G1 section 1.3 "Wrap".

Phases (each writes its JSON under OUT and is reused unless --force):

  lift    remill-lift-14 over the eleven functions this stage needs -- the ten
          S1 spike functions and 0x00426D50, the active point transform the S2
          entry test's 33 437 discriminating native rows came from -- with the
          spike's invocation (`unshare -Urm` with the semantics bind mount),
          then `tools/spike/pc24pass/pc24pass.py` over each result. Both the
          unpatched (fp80) and patched (pc24) IR are kept, because the entry
          test's evidence is a contrast between them.
  build   compile `runtime/` and `harness/` and every IR file with
          `zig cc -target x86_64-linux-musl -O2` (the pipeline
          `Documentation/receipts/s2-build-time-sample-v1.json` measured), and
          link one driver per (function, variant). The function table of each
          driver is generated by tools/s2/wrap/gen_function_table.py from
          private/generated/function-map.json and that driver's lifted defines.
  run     (a) the entry test's corpus rows through the runtime on 0x00426D50
          and 0x00426CC0, classified against the same two reference models;
          (b) the ten spike functions' fixture rows, compared both with the
          PC24 reference and with the S1 harness's own output files, byte for
          byte; plus the driver's own self-test of guest memory and the
          function table.
  receipt Documentation/receipts/s2-wrap-v1.json.

Everything generated lives under private/generated/s2/wrap/ (ignored). Nothing
under tools/spike or tools/s2/entry_test is modified; their modules are
imported read-only.

Usage:
  source tools/env.sh
  .venv/bin/python tools/s2/wrap/wrap.py [--phase lift|build|run|receipt] [--force]
"""
