def test_a_row_dropped_by_hand_stops_the_device_before_any_call(builds, tmp_path):
    """The count fixed up to the rows, the digest left: the device's own hash of its rows
    is not the header's, so the run stops at configuration and names both."""
    code, rec, err = probe(builds, "handedit", "mode", tmp_path)
    rows = header_rows(dropped_row(fix_count=True))
    assert len(rows) == listed_n() - 1
    full = ML.rows_digest(header_rows(HEADER.read_text()))
    assert code == 3 and rec == {}
    assert (f"d3d9 closed world: runtime/sa2_d3d9_m7_list.h's {listed_n() - 1} rows hash to "
            f"{ML.rows_digest(rows)[:16]}, not its SA2_D3D9_M7_LIST_DIGEST {full[:16]}: the rows "
            "were edited by hand; run tools/s4/m7_device_list.py") in err, err


def test_a_header_whose_count_is_not_its_rows_does_not_compile(builds, tmp_path):
    d, _exes, env = builds
    dev = tmp_path / "short" / "sa2_d3d9.c"
    dev.parent.mkdir()
    dev.write_text(D3D9_C.read_text())
    (dev.parent / "sa2_d3d9_m7_list.h").write_text(dropped_row(fix_count=False))
    done = compile_probe(dev, [], tmp_path / "probe-short", env)
    assert done.returncode != 0
    assert "the row count is not the rows; run tools/s4/m7_device_list.py" in done.stderr, done.stderr
