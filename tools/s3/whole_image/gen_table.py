#!/usr/bin/env python3
"""Generate the whole-image function table (design 3.4, "Indirect calls").

`tools/s2/wrap/gen_function_table.py` is the S2 generator and is left alone:
it reads every `.ll` it is given to find the defines, which is right for the
eleven modules a wrap driver links and wrong for 12 683 modules and 3.5 GB of
IR, and its `--ll` argument list would not fit in one `execve`. The rule it
emits by -- one row per lifted define, `{va, symbol, name}`, address-ordered,
skipping LLVM's `sub_<hex>.<n>` collision renames -- is reproduced here
exactly, from a source that is already on disk: `compile_all.py` recorded each
module's externally-defined symbols in `build/<tag>.jsonl` as it compiled it.

The table is lifted-derived output (it names lifted symbols), so it is written
under `private/generated/` only and never committed (AGENTS.md rule 9).

Usage:
  .venv/bin/python tools/s3/whole_image/gen_table.py --tag next \
      --out private/generated/s3/link/next/function_table_whole.c
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

# A real lifted entry point. LLVM's collision renames carry a `.<n>` suffix and
# are remill's dead missing-block stubs, not entry points.
SYMBOL = re.compile(r"^sub_[0-9a-fA-F]+$")


def rows(tag: str) -> tuple[list[tuple[int, str, str, str]], dict]:
    """(va, symbol, name, region) per lifted define, plus the census."""
    build = C.read_jsonl(C.BUILD / f"{tag}.jsonl")
    fmap = C.by_address()
    seen: dict[str, str] = {}
    duplicates: list[dict] = []
    out: list[tuple[int, str, str, str]] = []
    skipped: collections.Counter = collections.Counter()
    for rec in build.values():
        if not rec.get("compiled"):
            continue
        module = rec["va"]
        for sym in rec.get("defines", []):
            if not SYMBOL.match(sym):
                skipped[sym.split(".")[0] + ".<n>" if "." in sym else sym] += 1
                continue
            if sym in seen:
                duplicates.append({"symbol": sym, "modules": [seen[sym], module]})
                continue
            seen[sym] = module
            va = int(sym[len("sub_"):], 16)
            fn = fmap.get(va)
            out.append((va, sym, (fn or {}).get("name") or sym,
                        (fn or {}).get("region") or "unmapped"))
    out.sort()
    census = {
        "modules_compiled": sum(1 for r in build.values() if r.get("compiled")),
        "rows": len(out),
        "duplicate_symbols": duplicates,
        "non_entry_defines_skipped": sum(skipped.values()),
        "by_region": dict(collections.Counter(r[3] for r in out)),
        "map_entries_without_a_row": sorted(
            f"0x{va:08x}" for va in fmap if va not in {r[0] for r in out})[:40],
    }
    return out, census


def emit(rows_: list[tuple[int, str, str, str]], out: Path, tag: str) -> None:
    lines = [
        "/* GENERATED by tools/s3/whole_image/gen_table.py -- do not edit, do not commit.",
        f" * arm: {tag}   rows: {len(rows_)}",
        f" * generated: {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        " * Lifted-derived output: it names lifted symbols, so it lives under",
        " * private/generated only (AGENTS.md rule 9, design 10).",
        " */",
        '#include "function_table.h"',
        "",
    ]
    lines += [f"extern void *{sym}(void *state, uint32_t pc, void *memory);"
              for _va, sym, _n, _r in rows_]
    lines += ["", "static const sa2_ft_desc kGenerated[] = {"]
    lines += [f'    {{0x{va:08x}u, {sym}, "{name}"}},' for va, sym, name, _r in rows_]
    lines += [
        "};",
        "",
        "uint32_t sa2_ft_generated_count(void) {",
        "    return (uint32_t)(sizeof kGenerated / sizeof kGenerated[0]);",
        "}",
        "",
        "int sa2_ft_register_generated(void) {",
        "    return sa2_ft_add_all(kGenerated, sa2_ft_generated_count(), SA2_FN_LIFTED);",
        "}",
        "",
        "/* The link probe walks the same descriptors to measure the table's load",
        " * factor and probe depth; nothing else uses this. */",
        "const sa2_ft_desc *sa2_ft_generated_descs(void) { return kGenerated; }",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="next")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--json", type=Path, default=None)
    args = ap.parse_args()
    rows_, census = rows(args.tag)
    emit(rows_, args.out, args.tag)
    census["out"] = str(args.out)
    census["out_bytes"] = args.out.stat().st_size
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(census, indent=1, sort_keys=True) + "\n")
    print(f"{census['rows']} rows, {len(census['duplicate_symbols'])} duplicate symbols, "
          f"{census['non_entry_defines_skipped']} non-entry defines skipped -> {args.out}")


if __name__ == "__main__":
    main()
