def count(patterns: dict[str, str], paths: list[Path]) -> dict[str, int]:
    text = "\n".join(p.read_text(errors="replace") for p in paths if p.exists())
    return {k: len(re.findall(v, text)) for k, v in patterns.items()}


def tool_version(cmd: list[str]) -> str:
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        return (p.stdout + p.stderr).strip().splitlines()[0]
    except Exception as exc:  # noqa: BLE001
        return f"unavailable: {exc}"


def load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def fixture_fields(fx: dict | None, lifter_has_harness: bool) -> tuple[dict | str, str]:
    """(fixture block, pc24_check string) for one function under one lifter."""
    if fx is None:
        reason = NOT_ATTEMPTED if lifter_has_harness else NO_HARNESS
        return reason, reason
    L = fx["lifter"]
    block = {"rows": L.get("rows", 0), "passed": L.get("passed", 0), "exact": L.get("exact", 0), "residue": L.get("residue", 0),
             "failed": L.get("failed", 0), "not_run": L.get("not_run", 0), "verdict": L["verdict"],
             "native_rows": (L.get("rows_by_authority") or {}).get("native", 0),
             "discriminating_rows": fx["pc24_vs_fp80_model_differ_rows"],
             "rows_by_authority": L.get("rows_by_authority"), "exact_by_authority": L.get("exact_by_authority"),
             "coverage": L.get("coverage"), "observed_status_counts": L.get("observed_status_counts"),
             "expected_status_counts": L.get("expected_status_counts"),
             "first_divergent_row": (L.get("first_divergence") or {}).get("row"),
             "first_divergent_field": (L.get("first_divergence") or {}).get("field"),
             "first_divergence": L.get("first_divergence"), "first_fail": L.get("first_fail"),
             "blocker": L.get("blocker"), "run_stderr_head": L.get("run_stderr_head", ""),
             "fields": fx["fields"], "sources": fx["sources"], "vectors_sha256": fx["vectors_sha256"],
             "pc24_vs_fp80_model_differ_rows": fx["pc24_vs_fp80_model_differ_rows"]}
    v = L["verdict"]
    auth = ", ".join(f"{n} {a}" for a, n in (L.get("rows_by_authority") or {}).items())
    if v.startswith("EXACT"):
        check = f"{v}: {L['exact']}/{L['rows']} rows bit-identical ({auth})"
        if v.endswith("-PARTIAL"):
            check += "; every row exits at a callee outside the ten, only the head was checked"
    elif v == "RESIDUE-ONLY":
        check = f"RESIDUE-ONLY: {L['exact']}/{L['rows']} rows bit-identical, {L['residue']} differ from PC24 only where the 80-bit model predicts ({auth}); first at row {block['first_divergent_row']} field {block['first_divergent_field']}"
    elif v == "FAIL":
        fd = L.get("first_fail") or L.get("first_divergence") or {}
        check = f"FAIL: {L['exact']} exact, {L['residue']} residue, {L['failed']} failed of {L['rows']}; first failing row {fd.get('row')} field {fd.get('field')} expected {fd.get('expected')} observed {fd.get('observed')}"
        if fd.get("detail"):
            check += f" ({fd['detail'].splitlines()[0][:160]})"
    else:
        check = f"NOT-RUN: {L.get('blocker', '')}".strip()
    return block, check


def per_function(fn: dict, r: dict | None, output_keys: tuple[str, ...], fx: dict | None = None, lifter_has_harness: bool = False) -> dict:
    row = {"va": fn["va"], "name": fn["name"]}
    if r is None:
        row.update({"lifted": False, "lift_error_head": "lifter not installed", "compiled": {}, "output_lines": {}})
    else:
        row["lifted"] = r["lifted"]
        row["lift_error_head"] = r.get("lift_error_head", "")
        row["compiled"] = {k: {"ok": v["ok"], "error_head": v["error_head"].splitlines()[0][:200] if v["error_head"] else ""}
                           for k, v in r.get("compile", {}).items()}
        row["output_lines"] = {k: r[k] for k in output_keys if k in r}
        if "seconds" in r:
            row["lift_seconds"] = r["seconds"]
        if "missing_blocks" in r:
            row["remill_missing_block_calls"] = r["missing_blocks"]
    row["fixture"], row["pc24_check"] = fixture_fields(fx, lifter_has_harness)
    return row


def fixture_for(fixtures: dict | None, lifter: str, va: str) -> dict | None:
    if not fixtures:
        return None
    fn = fixtures["functions"].get(va.lower()) or fixtures["functions"].get(f"{int(va, 16):#010x}")
    if not fn or lifter not in fn["lifters"]:
        return None
    return {"lifter": fn["lifters"][lifter], "fields": fn["fields"], "sources": fn["sources"], "vectors_sha256": fn["vectors_sha256"],
            "pc24_vs_fp80_model_differ_rows": fn["pc24_vs_fp80_model_differ_rows"]}


def design_rule(n: int) -> str:
    return "adopt (>= 8/10)" if n >= 8 else ("base for pivot (6-7/10)" if n >= 6 else "custom emitter (< 6/10)")


def fixture_verdict(rows: list[dict]) -> dict:
    verdicts = [r["fixture"]["verdict"] if isinstance(r["fixture"], dict) else "NOT-ATTEMPTED" for r in rows]
    exact = verdicts.count("EXACT")
    exact_partial = verdicts.count("EXACT-PARTIAL")
    residue = verdicts.count("RESIDUE-ONLY")
    fail = verdicts.count("FAIL")
    not_run = verdicts.count("NOT-RUN") + verdicts.count("NOT-ATTEMPTED")
    return {"functions_exact": exact, "functions_exact_partial_head_only": exact_partial, "functions_residue_only": residue,
            "functions_fail": fail, "functions_not_run": not_run, "of": len(rows),
            "per_function": {r["va"]: v for r, v in zip(rows, verdicts)},
            "rule_on_exact": {"passing": exact, "verdict": design_rule(exact)},
            "rule_on_exact_plus_residue": {"passing": exact + residue, "verdict": design_rule(exact + residue)},
            "rule_counting_partial_heads": {"passing": exact + exact_partial + residue, "verdict": design_rule(exact + exact_partial + residue)},
            "definition": "design 5 S1: >= 8/10 with a fixable remainder -> adopt; 6-7/10 -> base for pivot; else custom emitter. EXACT-PARTIAL (only the head ran, every row exited at a callee outside the ten) is not counted as passing in the first two rules"}


def reproduced(text: str | None) -> int:
    """'53/53' -> 53 (the native rows a reference model reproduces); None -> 0."""
    return int(text.split("/")[0]) if text else 0


def ten_function_table(rows: list[dict]) -> dict:
    """Per function: verdict beside the native-row and discriminating-row counts; per lifter: the totals.

    discriminating_rows = rows of that function's vectors where the PC24 and fp80 reference models give
    different words (pc24_vs_fp80_model_differ_rows from run_fixtures.py); an EXACT verdict over zero such
    rows says nothing about precision control. native_rows = rows_by_authority.native (directly traced),
    the rest are against the statically-translated reference."""
    table = []
    for r in rows:
        f = r["fixture"]
        if not isinstance(f, dict):
            table.append({"va": r["va"], "name": r["name"], "verdict": "NOT-ATTEMPTED"})
            continue
        nat = (f["sources"].get("native") or {}) if isinstance(f.get("sources"), dict) else {}
        table.append({"va": r["va"], "name": r["name"], "verdict": f["verdict"], "rows": f["rows"], "native_rows": f["native_rows"],
                      "discriminating_rows": f["discriminating_rows"], "exact": f["exact"], "residue": f["residue"], "failed": f["failed"],
                      "native_rows_reproduced_by_pc24_model": reproduced(nat.get("pc24_reference_reproduces_rows")),
                      "native_rows_reproduced_by_fp80_model": reproduced(nat.get("fp80_model_reproduces_rows"))})
    done = [t for t in table if "rows" in t]
    totals = {k: sum(t[k] for t in done) for k in ("rows", "native_rows", "discriminating_rows", "exact", "residue", "failed",
                                                     "native_rows_reproduced_by_pc24_model", "native_rows_reproduced_by_fp80_model")}
    totals["functions_with_zero_discriminating_rows"] = [f"{t['va']} {t['name']}".strip() + f" ({t['verdict']})" for t in done if t["discriminating_rows"] == 0]
    totals["exact_functions_with_zero_discriminating_rows"] = sum(1 for t in done if t["discriminating_rows"] == 0 and t["verdict"] == "EXACT")
    return {"definition": "verdict per function beside native_rows (rows_by_authority.native: directly traced from the predecessor's fixture) and "
                          "discriminating_rows (rows where the PC24 and fp80 reference models differ, run_fixtures.py pc24_vs_fp80_model_differ_rows); "
                          "an EXACT verdict over zero discriminating rows does not test precision control; native rows are reproduced by both models "
                          "(the natural matrix is an axis permutation), so they anchor the reference, not the PC24 question",
            "per_function": table, "totals": totals}


def headline(fv: dict) -> str:
    n, of = fv["rule_on_exact_plus_residue"]["passing"], fv["of"]
    tail = " (residue entirely the 80-bit model = the fixable remainder)" if fv["functions_fail"] == 0 and fv["functions_residue_only"] else ""
    return f"{n}/{of} EXACT+RESIDUE{tail}"


def fixture_limits(fns: list[dict], fixtures: dict, remill_rows: list[dict]) -> list[dict]:
    """What the fixture corpus does not exercise, measured from the generated files where it can be."""
    harness = HARNESS_SRC.read_text() if HARNESS_SRC.exists() else ""
    cw_sites = harness.count("cwd.flat = 0x007F")
    ir = {f["va"]: (GEN / "remill" / f"sub_{int(f['va'], 16):08X}.ll") for f in fns}
    ir_text = {va: (p.read_text() if p.exists() else "") for va, p in ir.items()}
    fp80_ops = {va: len(re.findall(X87_PATTERNS["fp80_arith_ops"], t)) for va, t in ir_text.items()}
    fsqrt_labels = sum(t.count("FSQRT") for t in ir_text.values())
    fldcw_labels = sum(t.count("FLDCW") for t in ir_text.values())
    by_va = {r["va"]: r for r in remill_rows}
    zero_op_exact = [f"{va} {by_va[va]['name']}".strip() for va in fp80_ops if fp80_ops[va] == 0 and isinstance(by_va[va]["fixture"], dict) and by_va[va]["fixture"]["verdict"] == "EXACT"]
    zero_op_all = [f"{va} {by_va[va]['name']}".strip() + f" ({by_va[va]['fixture']['verdict'] if isinstance(by_va[va]['fixture'], dict) else 'NOT-ATTEMPTED'})" for va in fp80_ops if fp80_ops[va] == 0]
    transform_dir = next((r for r in remill_rows if r["va"].lower() == "0x00468fa0"), None)
    td = transform_dir["fixture"] if transform_dir and isinstance(transform_dir["fixture"], dict) else {}
    return [
        {"item": "control word never varied", "authority": "measured",
         "finding": f"every fixture row runs under control word 0x007F: remill_harness.cpp sets state.x87.fxsave.cwd.flat = 0x007F per row ({cw_sites} assignment site), "
                    f"no vector carries a control word, and the ten lifted files contain {fldcw_labels} FLDCW semantic labels; PC53 (0x027F) and PC64 (0x037F) behaviour of "
                    "lifted code is untested here (the pc24pass helper is tested against the host x87 at PC53 natively, s1-remill-pc24-patch-v1.json helper_selftest, "
                    "but no lifted row ran under it)"},
        {"item": "fsqrt served natively", "authority": "measured",
         "finding": f"the game's sqrt is a call to the CRT's _CIsqrt (0x8290a0), which the harness executes as a host fsqrt under the guest control word "
                    f"(remill_harness.cpp sub_8290a0); the ten lifted files contain {fsqrt_labels} FSQRT semantic labels, so remill's FSQRT semantics never ran "
                    "and every sqrt result in the table is the host's, PC24-exact by construction"},
        {"item": "0x00468FA0 transform_dir: the 0x459260 callee is an oracle stub", "authority": "measured",
         "finding": f"the harness answers 0x459260 (direction -> two angles) by writing the fixture row's own expected angles into guest memory (remill_harness.cpp sub_459260), "
                    f"and sub_00468FA0.ll has {fp80_ops.get('0x00468fa0', fp80_ops.get('0x00468FA0', 0))} x86_fp80 arithmetic ops of its own; "
                    f"{(td.get('coverage') or {}).get('rows_returned_through_ret')} of {td.get('rows')} rows return (zero rotation angles) with {td.get('residue')} residue rows, "
                    "so the float words of its EXACT verdict are the stub's output and the identity path, not lifted x87 evidence"},
        {"item": "EXACT functions with no x87 arithmetic", "authority": "measured",
         "finding": f"{len(zero_op_exact)} of the EXACT functions have zero x86_fp80 arithmetic ops in their lifted IR ({', '.join(zero_op_exact)}); "
                    f"all functions with zero ops: {', '.join(zero_op_all)}; their EXACT verdicts test control flow, integer logic, memory and the "
                    "matrix-stack globals, not precision control (their discriminating_rows are 0 in the ten-function table)"},
        {"item": "reference softness", "authority": "reasoned",
         "finding": "the pc24 model rounds in double then to 24 bits (RoundSignificand24), which can double-round on sums whose exponents differ by more than 29 "
                    "and on sqrt; no synthetic row hit it (every remill divergence matched fp80, none matched neither)"},
    ]


def tally(rows: list[dict]) -> dict:
    kinds = sorted({k for row in rows for k in row["compiled"]})
    return {"lifted": sum(r["lifted"] for r in rows), "of": len(rows),
            "compiled": {k: sum(r["compiled"].get(k, {}).get("ok", False) for r in rows) for k in kinds}}


