#!/usr/bin/env python3
"""Generate the runtime's function table from the function map and a set of lifted IR files.

Design 3.4, "Indirect calls": *a hash table from original address to lifted
function pointer, built at startup from the function map, as XenonRecomp does*.
The table itself is `runtime/function_table.c` (tracked, original C); the
*contents* are generated here, because they name lifted symbols and are
therefore lifted-derived output that must never be committed (AGENTS.md rule 9).

Input:
  --map   private/generated/function-map.json, for each entry's name, region
          and size. An address the map does not contain is emitted anyway, with
          `region` "unmapped", because a lifted define that the map lost is a
          fact about the lift and hiding it would be worse.
  --ll    the lifted `.ll` files that will be linked into this program. Only
          real defines count: `define ... @sub_<hex>(`. LLVM's collision
          renames (`@sub_<hex>.<n>`) are remill's dead missing-block stubs, not
          entry points, and are skipped.

Output: one C file under private/generated (never tracked) defining
  `sa2_ft_generated_count()` and `sa2_ft_register_generated()`, which
  `sa2_runtime_init` calls before anything runs.

Usage:
  .venv/bin/python tools/s2/wrap/gen_function_table.py \
      --map private/generated/function-map.json \
      --out private/generated/s2/wrap/gen/function_table_calc_point.c \
      --ll  private/generated/s2/wrap/lift/sub_00426CC0.pc24.ll
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
from pathlib import Path

DEFINE = re.compile(r"^define\s[^@\n]*@(sub_[0-9a-fA-F]+)\(", re.M)


def lifted_symbols(paths: list[Path]) -> list[tuple[str, int, str]]:
    """(symbol, va, source file) for every real lifted define, address-ordered."""
    found: dict[str, tuple[int, str]] = {}
    for p in paths:
        text = p.read_text(errors="replace")
        for sym in DEFINE.findall(text):
            va = int(sym[len("sub_"):], 16)
            if sym in found and found[sym][1] != p.name:
                raise SystemExit(f"{sym} is defined in both {found[sym][1]} and {p.name}: "
                                 "linking both would be a duplicate symbol")
            found.setdefault(sym, (va, p.name))
    return sorted(((s, va, src) for s, (va, src) in found.items()), key=lambda r: r[1])


def load_map(path: Path) -> dict[int, dict]:
    data = json.loads(path.read_text())
    return {int(f["address"], 16): f for f in data["functions"]}


def emit(syms: list[tuple[str, int, str]], fmap: dict[int, dict], out: Path, map_path: str) -> dict:
    lines = [
        "/* GENERATED by tools/s2/wrap/gen_function_table.py -- do not edit, do not commit.",
        f" * map: {map_path}",
        f" * generated: {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        " * Lifted-derived output: it names lifted symbols, so it lives under",
        " * private/generated only (AGENTS.md rule 9, design 10).",
        " */",
        '#include "function_table.h"',
        "",
    ]
    for sym, _va, _src in syms:
        lines.append(f"extern void *{sym}(void *state, uint32_t pc, void *memory);")
    lines += ["", "static const sa2_ft_desc kGenerated[] = {"]
    stats = {"game": 0, "crt": 0, "cri": 0, "other": 0, "unmapped": 0}
    for sym, va, _src in syms:
        fn = fmap.get(va)
        region = fn["region"] if fn else "unmapped"
        stats[region] = stats.get(region, 0) + 1
        name = (fn or {}).get("name") or sym
        lines.append(f'    {{0x{va:08x}u, {sym}, "{name}"}},   /* {region} */')
    lines += [
        "};",
        "",
        "uint32_t sa2_ft_generated_count(void) {",
        "    return (uint32_t)(sizeof kGenerated / sizeof kGenerated[0]);",
        "}",
        "",
        "int sa2_ft_register_generated(void) {",
        "    return sa2_ft_add_all(kGenerated, sa2_ft_generated_count(), SA2_FN_LIFTED);",
        "}",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    return {"entries": len(syms), "by_region": stats,
            "addresses": [f"0x{va:08x}" for _s, va, _src in syms]}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--map", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--ll", required=True, nargs="+", type=Path)
    ap.add_argument("--json", type=Path, help="write the generation summary here")
    args = ap.parse_args()
    syms = lifted_symbols(args.ll)
    summary = emit(syms, load_map(args.map), args.out, str(args.map))
    summary["out"] = str(args.out)
    summary["ll"] = [str(p) for p in args.ll]
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(summary, indent=1) + "\n")
    print(json.dumps(summary["by_region"], sort_keys=True), summary["entries"], "entries ->", args.out)


if __name__ == "__main__":
    main()
