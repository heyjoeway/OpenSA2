#!/usr/bin/env python3
"""Generate the d3d9gpu COM stub bases from the pinned DXVK Native d3d9.h.

Subtitle: every method of the eleven interfaces host/player calls is read from the header's
DECLARE_INTERFACE_ blocks, in vtable order, and given a default body. A default records
the call as not implemented (d9g::not_implemented, by interface index and slot) and
answers D3DERR_INVALIDCALL; one returning ULONG, UINT, DWORD, BOOL or float answers 0, an
enum answers its zero value, and a void one returns. The device's classes override only
what they implement, so a method nobody wrote is counted by name in the device's report
instead of being typed out by hand. QueryInterface, AddRef and Release (slots 0 to 2) are
the classes' own.

Outputs, both generated and never tracked:
  OUT/d9g_com_stubs.h  struct D9gStub_<Interface> : public <Interface> { ... }; and, in
                       namespace d9g_gen, each interface's name and its methods' names by slot
  OUT/d9g_slots.json   {"<Interface>": [method names in slot order], ...}, which
                       Documentation/scripts/tests/test_s5_d3d9gpu.py holds to
                       host/player/names.h (the recorder's slot numbering).

Usage:
  python3 host/d3d9gpu/gen_com.py --header private/s5-tools/install/include/dxvk/d3d9.h --out DIR
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# The interfaces host/player calls, with the names host/player/names.h gives them.
INTERFACES = {
    "IDirect3D9": "IDirect3D9",
    "IDirect3DDevice9": "Device",
    "IDirect3DTexture9": "Texture",
    "IDirect3DSurface9": "Surface",
    "IDirect3DVertexBuffer9": "VertexBuffer",
    "IDirect3DIndexBuffer9": "IndexBuffer",
    "IDirect3DVertexDeclaration9": "VertexDeclaration",
    "IDirect3DVertexShader9": "VertexShader",
    "IDirect3DPixelShader9": "PixelShader",
    # Appended, so the nine above keep their indices (d9g.h Iface) and every earlier report its
    # names: the cube and volume textures (d9g_resources.cpp CubeTexture, VolumeTexture).
    "IDirect3DCubeTexture9": "CubeTexture",
    "IDirect3DVolumeTexture9": "VolumeTexture",
}
# Default answers by return type; anything else is refused, so a new type is a decision.
DEFAULTS = {
    "HRESULT": "D3DERR_INVALIDCALL",
    "ULONG": "0", "UINT": "0", "DWORD": "0", "BOOL": "FALSE", "WINBOOL": "FALSE", "float": "0.0f",
    "D3DRESOURCETYPE": "D3DRESOURCETYPE(0)", "D3DTEXTUREFILTERTYPE": "D3DTEXF_NONE",
    "HMONITOR": "nullptr", "void": None,
}
METHOD = re.compile(r"STDMETHOD(?:_\(\s*([A-Za-z_][\w ]*?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\((.*)\)\s*PURE$",
                    re.S)


def methods(header: str, interface: str) -> list[tuple[str, str, str]]:
    """(return type, name, parameter list) for each method of `interface`, in vtable order."""
    m = re.search(r"DECLARE_INTERFACE_\(\s*" + interface + r"\s*,\s*\w+\s*\)\s*\{(.*?)\n\};", header, re.S)
    if not m:
        raise ValueError(f"{interface}: no DECLARE_INTERFACE_ block")
    body = re.sub(r"/\*.*?\*/", " ", m.group(1), flags=re.S)
    out = []
    for stmt in body.split(";"):
        stmt = " ".join(stmt.split())
        if not stmt:
            continue
        mm = METHOD.fullmatch(stmt)
        if not mm:
            raise ValueError(f"{interface}: cannot read {stmt!r}")
        ret, name = (mm.group(1), mm.group(2)) if mm.group(2) else ("HRESULT", mm.group(3))
        params = mm.group(4).strip()
        if params == "THIS":
            params = ""
        elif params.startswith("THIS_"):
            params = params[len("THIS_"):].strip()
        else:
            raise ValueError(f"{interface}::{name}: parameters do not start with THIS: {params!r}")
        out.append((" ".join(ret.split()), name, params))
    return out


def generate(header_path: Path, out: Path) -> dict:
    header = header_path.read_text()
    slots: dict[str, list[str]] = {}
    text = ["// Generated by host/d3d9gpu/gen_com.py from " + header_path.name + "; do not edit.",
            "#pragma once", "#include <windows.h>", "#include <d3d9.h>", '#include "d9g_ni.h"', ""]
    for index, (iface, short) in enumerate(INTERFACES.items()):
        rows = methods(header, iface)
        if [r[1] for r in rows[:3]] != ["QueryInterface", "AddRef", "Release"]:
            raise ValueError(f"{iface}: slots 0-2 are not IUnknown's")
        slots[iface] = [r[1] for r in rows]
        text.append(f"struct D9gStub_{iface} : public {iface} {{")
        for slot, (ret, name, params) in enumerate(rows):
            if slot < 3:
                continue
            if ret not in DEFAULTS:
                raise ValueError(f"{iface}::{name}: no default for return type {ret!r}")
            note = f'::d9g::not_implemented({index}, {slot});'
            value = DEFAULTS[ret]
            body = f"{note} return {value};" if value is not None else note
            text.append(f"    {ret} STDMETHODCALLTYPE {name}({params}) override {{ {body} }}")
        text.append("};")
        text.append("")
    # The names by interface index (INTERFACES' order) and slot, for the device's report.
    text.append("namespace d9g_gen {")
    text.append(f"constexpr int kInterfaces = {len(INTERFACES)};")
    text.append("inline const char* const kInterfaceName[] = {" +
                ", ".join(f'"{s}"' for s in INTERFACES.values()) + "};")
    for iface in INTERFACES:
        text.append(f"inline const char* const kSlots_{iface}[] = {{" + ", ".join(f'"{n}"' for n in slots[iface]) + "};")
    text.append("inline const char* const* const kSlotNames[] = {" + ", ".join(f"kSlots_{i}" for i in INTERFACES) + "};")
    text.append("inline const unsigned kSlotCount[] = {" + ", ".join(str(len(slots[i])) for i in INTERFACES) + "};")
    text.append("}  // namespace d9g_gen")
    text.append("")
    out.mkdir(parents=True, exist_ok=True)
    (out / "d9g_com_stubs.h").write_text("\n".join(text))
    (out / "d9g_slots.json").write_text(json.dumps(slots, indent=1) + "\n")
    return slots


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--header", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args(argv)
    try:
        slots = generate(a.header, a.out)
    except (OSError, ValueError) as exc:
        print(f"gen_com: {exc}", file=sys.stderr)
        return 2
    print("gen_com: " + ", ".join(f"{k} {len(v)}" for k, v in slots.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
