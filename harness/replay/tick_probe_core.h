/* The row format of a tick capture, shared by the native hook and the lifted
 * wrapper so that the two files differ only where the game's state does.
 *
 * Format: a header `tick,<field>...`, then one row per tick, the tick in
 * decimal and every field as `0x%08x` -- raw words, never formatted floats,
 * because the native side prints with mingw's printf and the lifted side with
 * musl's, and a decimal float is where two libcs are allowed to disagree. This
 * is the input contract of Omochao Split (compare_sa2_record_streams.py).
 *
 * The includer defines, before including this file:
 *
 *     static uint32_t tp_read(uint32_t va, unsigned width);
 *
 * returning the zero-extended little-endian value of `width` bytes at `va`,
 * and says which row it writes, one way or the other; neither is an error, so
 * an includer cannot get the other row by leaving something out:
 *
 *   - The named fields and the digest columns: include a digest mask first
 *     (tick_digest.h, or a stage's), and define
 *
 *         static const uint32_t *tp_block(uint32_t va, uint32_t bytes);
 *
 *     returning a host pointer to `bytes` of guest memory at `va`, or NULL when
 *     it cannot be read. The lifted wrapper (wrap_tick_probe.c) writes this row,
 *     and so does the host reader of the word log (tools/s4/wordlog.c), which
 *     gives it the words a log rebuilds for each tick.
 *
 *   - The named fields alone: define TP_NO_DIGEST. The native probe
 *     (native_tick_probe.c) writes this row since it logs every word of
 *     `.dataa` (word_log_core.h): the game no longer computes the digests, the
 *     host computes the same columns from the log with this file's td_digest,
 *     and the mask is not among the native probe's inputs, so a new mask is
 *     not a new configuration of the native game (judge-plan.md, "Verdict").
 *
 * The digest columns, `d_<block>`, are one per 64 KiB block of `.dataa` the
 * mask lists: a 32-bit FNV-1a over the block's selected words, taken whole
 * (h = (h ^ word) * 16777619), in address order. tick_digest.h is generated by
 * tools/s4/snapshot_fields.py and selects every word native runs agree on that
 * varies and does not hold an address, so a replay compares the game's varying
 * data, not only the words GameLoop names. An unreadable block reads
 * 0xFFFFFFFF.
 */
#ifndef SA2_TICK_PROBE_CORE_H
#define SA2_TICK_PROBE_CORE_H

#include <stdint.h>
#include <stdio.h>

#if defined(TP_NO_DIGEST) && defined(TD_BLOCKS)
#error "TP_NO_DIGEST with a digest mask included: a row has the digest columns or it does not"
#endif
#if !defined(TP_NO_DIGEST) && !defined(TD_BLOCKS)
#error "include a digest mask (tick_digest.h) before tick_probe_core.h for the digest columns, or define TP_NO_DIGEST for the named fields alone"
#endif

#ifdef TD_BLOCKS
static uint32_t td_digest(unsigned b) {
    const uint32_t base = td_base[b];
    const uint32_t bytes = TD_DATA_END - base < 0x10000u ? TD_DATA_END - base : 0x10000u;
    const uint32_t *w = tp_block(base, bytes);
    if (!w)
        return 0xFFFFFFFFu;
    uint32_t h = 2166136261u;
    for (unsigned k = 0; k < 512; ++k) {
        uint32_t m = td_mask[b][k];
        while (m) {
            const unsigned i = (unsigned)__builtin_ctz(m);
            m &= m - 1;
            h = (h ^ w[k * 32 + i]) * 16777619u;
        }
    }
    return h;
}
#endif

static void tp_write_header(FILE *out) {
    fputs("tick", out);
#define TP_FIELD(name, va, width) fputs("," #name, out);
#include "tick_fields.h"
#undef TP_FIELD
#ifdef TD_BLOCKS
    for (unsigned b = 0; b < TD_BLOCKS; ++b)
        fprintf(out, ",d_%08x", (unsigned)td_base[b]);
#endif
    fputc('\n', out);
}

static void tp_write_row(FILE *out, unsigned long tick) {
    fprintf(out, "%lu", tick);
#define TP_FIELD(name, va, width) fprintf(out, ",0x%08x", (unsigned)tp_read((va), (width)));
#include "tick_fields.h"
#undef TP_FIELD
#ifdef TD_BLOCKS
    for (unsigned b = 0; b < TD_BLOCKS; ++b)
        fprintf(out, ",0x%08x", (unsigned)td_digest(b));
#endif
    fputc('\n', out);
}

#endif
