# ---------------------------------------------------------------- utilities
def now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def cmdline(cmd: list[str]) -> str:
    return " ".join(cmd).replace(str(ROOT) + "/", "")


def sh(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def dump(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=1) + "\n")


def load(path: Path):
    return json.loads(path.read_text())


def read_out(path: Path) -> list[list[int]]:
    data = path.read_bytes()
    assert data[:8] == b"SA2FXO1\0", path
    _va, rows, words = struct.unpack_from("<3I", data, 8)
    return [list(struct.unpack_from(f"<{words}I", data, 20 + i * words * 4)) for i in range(rows)]


def write_vectors(path: Path, va: int, in_words: int, out_words: int, rows: list[list[int]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as f:
        f.write(b"SA2FXV1\0")
        f.write(struct.pack("<4I", va, len(rows), in_words, out_words))
        for r in rows:
            assert len(r) == in_words
            f.write(struct.pack(f"<{in_words}I", *r))


def memory_image() -> bytes:
    """The PE's memory-mapped image, for the lifter's `--bytes`."""
    import pefile
    pe = pefile.PE(str(EXE), fast_load=True)
    return bytes(pe.get_memory_mapped_image())


# ---------------------------------------------------------------- phase: lift
def function_bytes() -> dict[int, bytes]:
    """The byte range lifted per function: the S1 spike's own ranges for the
    ten (so the re-run is of the same code), and 0x00426D50's entry-to-first-ret
    range, derived from the image with iced-x86 exactly as the entry test does."""
    out: dict[int, bytes] = {}
    for fn in S.functions():
        va = int(fn["va"], 16)
        p = Path(fn["bin"])
        out[va] = (ROOT / p).read_bytes() if not fn["bin"].startswith("/") else p.read_bytes()
    img = memory_image()
    _ops, end = ET.x87_sequence(img, CALC_POINT_ACTIVE)
    out[CALC_POINT_ACTIVE] = img[CALC_POINT_ACTIVE - 0x400000: end - 0x400000]
    return out


def trim_stats(stats: dict) -> dict:
    """The pass's stats carry a per-site list; the receipt wants the census."""
    keep = ("ops_instrumented", "by_op", "by_semantic", "by_function", "already_instrumented",
            "skipped_non_lifted", "skipped_already_wrapped", "int_helper", "fist_rewrites",
            "by_fist_semantic", "fix_control_word", "control_word_masks_fixed",
            "fpatan_rewrites", "fpatan_refused", "f80_accessor_attrs_fixed",
            "input_lines", "output_lines", "output_sha256")
    return {k: stats[k] for k in keep if k in stats}


def phase_lift(force: bool) -> dict:
    js = OUT / "lift.json"
    if js.exists() and not force:
        return load(js)
    lift_dir = OUT / "lift"
    lift_dir.mkdir(parents=True, exist_ok=True)
    blobs = function_bytes()
    log: dict = {"written": now(), "helper_ll": rel(HELPER_LL), "helper_sha256": sha(HELPER_LL), "functions": {}}
    for _name, va, _callees in TARGETS:
        raw = blobs[va]
        ll = lift_dir / f"sub_{va:08X}.ll"
        inner = (f"mount --bind {REMILL_PREFIX} /usr/local && /usr/local/bin/remill-lift-14 --arch x86 --os windows "
                 f"--address {va:#x} --bytes {raw.hex()} --ir_out {ll}")
        cmd = ["unshare", "-Urm", "--propagation", "unchanged", "sh", "-c", inner]
        t0 = time.time()
        p = sh(cmd, timeout=600)
        secs = round(time.time() - t0, 3)
        text = ll.read_text(errors="replace") if ll.exists() else ""
        lifted = p.returncode == 0 and re.search(rf"^define [^\n]*@sub_{va:x}\(", text, re.M) is not None
        entry = {
            "va": f"0x{va:08x}", "bytes": len(raw), "seconds": secs, "rc": p.returncode, "lifted": lifted,
            "command": f"unshare -Urm --propagation unchanged sh -c '{inner.replace(raw.hex(), f'<{len(raw)} bytes hex>')}'".replace(str(ROOT) + "/", ""),
            "ll": rel(ll), "ll_lines": text.count("\n"),
            "missing_blocks": len(re.findall(r"__remill_missing_block", text)),
            "error_head": "" if lifted else S.error_head(p.stderr + p.stdout),
        }
        if lifted:
            entry["ll_sha256"] = sha(ll)
            patched = lift_dir / f"sub_{va:08X}.pc24.ll"
            stats = lift_dir / f"sub_{va:08X}.pc24.stats.json"
            cmd2 = [sys.executable, str(PASS / "pc24pass.py"), "--helper-ll", str(HELPER_LL),
                    "--int-helper-ll", str(LS.int_helper_ll()),
                    str(ll), str(patched), "--stats", str(stats)]
            p2 = sh(cmd2)
            entry["pass"] = {"command": cmdline(cmd2), "rc": p2.returncode,
                             "error_head": S.error_head(p2.stderr) if p2.returncode else "",
                             "ll": rel(patched), "ll_sha256": sha(patched) if patched.exists() else None,
                             "stats": trim_stats(load(stats)) if stats.exists() else None}
        log["functions"][f"0x{va:08x}"] = entry
        print(f"lift {va:#010x} lifted={lifted} {secs}s lines={entry['ll_lines']}")
    log["lifted"] = sum(1 for e in log["functions"].values() if e["lifted"])
    log["instrumented_ops"] = sum((e.get("pass", {}).get("stats") or {}).get("ops_instrumented", 0)
                                  for e in log["functions"].values())
    dump(js, log)
    return log


# ---------------------------------------------------------------- phase: build
def cc(args: list[str], out: Path, cwd: Path) -> dict:
    cmd = [ZIG] + args + ["-o", str(out)]
    p = sh(cmd, cwd=cwd)
    return {"ok": p.returncode == 0, "command": cmdline(cmd),
            "error_head": S.error_head(p.stderr or p.stdout) if p.returncode else ""}


def phase_build(force: bool) -> dict:
    js = OUT / "build.json"
    if js.exists() and not force:
        return load(js)
    bdir = OUT / "build"
    gdir = OUT / "gen"
    bdir.mkdir(parents=True, exist_ok=True)
    gdir.mkdir(parents=True, exist_ok=True)
    lift = load(OUT / "lift.json")
    log: dict = {"written": now(), "target": " ".join(TARGET), "opt": OPT,
                 "runtime": {}, "harness": {}, "generated_tables": {}, "ir": {}, "link": {}}

    cflags = ["cc"] + TARGET + [OPT, "-w", "-c", "-I", str(RUNTIME), "-I", str(HARNESS)]
    for src in RUNTIME_C:
        log["runtime"][src] = cc(cflags + [str(RUNTIME / src)], bdir / (Path(src).stem + ".o"), bdir)
    for src in RUNTIME_CXX:
        log["runtime"][src] = cc(["c++"] + TARGET + [OPT, "-w", "-std=c++17", "-c", "-I", str(RUNTIME),
                                                     "-I", str(REMILL_INC), str(RUNTIME / src)],
                                 bdir / (Path(src).stem + ".o"), bdir)
    for src in HARNESS_C:
        log["harness"][src] = cc(cflags + [str(HARNESS / src)], bdir / (Path(src).stem + ".o"), bdir)

    base_objs = [str(bdir / (Path(s).stem + ".o")) for s in RUNTIME_C + RUNTIME_CXX + HARNESS_C]

    for variant in VARIANTS:
        suffix = ".ll" if variant == "fp80" else ".pc24.ll"
        for va in {t[1] for t in TARGETS} | {c for t in TARGETS for c in t[2]}:
            ll = OUT / "lift" / f"sub_{va:08X}{suffix}"
            o = bdir / f"ir_{variant}_{va:08X}.o"
            log["ir"][f"{variant}:0x{va:08x}"] = cc(["cc"] + TARGET + [OPT, "-w", "-c", str(ll)], o, bdir)

    for name, va, callees in TARGETS:
        for variant in VARIANTS:
            suffix = ".ll" if variant == "fp80" else ".pc24.ll"
            lls = [OUT / "lift" / f"sub_{v:08X}{suffix}" for v in [va] + callees]
            gen_c = gdir / f"function_table_{name}_{variant}.c"
            gen_js = gdir / f"function_table_{name}_{variant}.json"
            cmd = [sys.executable, str(HERE / "gen_function_table.py"), "--map", str(MAP),
                   "--out", str(gen_c), "--json", str(gen_js), "--ll"] + [str(p) for p in lls]
            p = sh(cmd)
            log["generated_tables"][f"{name}:{variant}"] = {
                "command": cmdline(cmd), "rc": p.returncode,
                "error_head": S.error_head(p.stderr) if p.returncode else "",
                "summary": load(gen_js) if gen_js.exists() else None,
                "sha256": sha(gen_c) if gen_c.exists() else None}
            if p.returncode:
                continue
            gen_o = bdir / f"function_table_{name}_{variant}.o"
            c = cc(cflags + [str(gen_c)], gen_o, bdir)
            log["generated_tables"][f"{name}:{variant}"]["compile"] = c
            if not c["ok"]:
                continue
            ir_objs = [str(bdir / f"ir_{variant}_{v:08X}.o") for v in [va] + callees]
            binary = bdir / f"{name}_{variant}"
            log["link"][f"{name}:{variant}"] = cc(["c++"] + TARGET + [OPT] + base_objs + [str(gen_o)] + ir_objs,
                                                  binary, bdir)
            if log["link"][f"{name}:{variant}"]["ok"]:
                log["link"][f"{name}:{variant}"]["binary"] = rel(binary)
                log["link"][f"{name}:{variant}"]["binary_sha256"] = sha(binary)

    log["lift_functions"] = lift["lifted"]
    log["objects_ok"] = all(e["ok"] for e in list(log["runtime"].values()) + list(log["harness"].values()) + list(log["ir"].values()))
    log["links_ok"] = sum(1 for e in log["link"].values() if e["ok"])
    log["links_total"] = len(log["link"])
    log["missing_symbols"] = sorted({m for e in log["link"].values() if not e["ok"]
                                     for m in re.findall(r"undefined symbol: (\S+)", e["error_head"])})
    dump(js, log)
    print(f"build: {log['links_ok']}/{log['links_total']} drivers linked")
    return log


# ---------------------------------------------------------------- phase: run
def classify(native: list[int], pc24: list[int], fp80: list[int]) -> str:
    return ET.classify(native, pc24, fp80)


def run_binary(binary: Path, vec: Path, out: Path) -> dict:
    t0 = time.time()
    p = sh([str(binary), str(EXE), str(vec), str(out)], timeout=3600)
    return {"command": cmdline([str(binary), str(EXE), str(vec), str(out)]), "rc": p.returncode,
            "seconds": round(time.time() - t0, 3), "stderr_tail": "\n".join(p.stderr.strip().splitlines()[-3:])}


def suite_entry_test(build: dict) -> dict:
    """Re-run the S2 entry test's rows through runtime v0."""
    vdir = OUT / "vectors"
    odir = OUT / "out"
    odir.mkdir(parents=True, exist_ok=True)
    result: dict = {"reference": {"binary": rel(REFERENCE), "sha256": sha(REFERENCE),
                                  "source": "tools/spike/fixtures/pc24_reference.c"},
                    "fixtures": [], "totals": {}}
    totals: dict = {}
    for entry in ET.survey():
        if entry["magic"] not in ET.DECODERS:
            continue
        p = ROOT / entry["fixture"]
        decode, _va = ET.DECODERS[entry["magic"]]
        ins, native, _meta = decode(p.read_bytes())
        name = p.stem
        vec_cp = vdir / f"{name}.calc_point.bin"
        vec_ac = vdir / f"{name}.calc_point_active.bin"
        write_vectors(vec_cp, CALC_POINT, 16, 3, ins)
        write_vectors(vec_ac, CALC_POINT_ACTIVE, 15, 3, [r[:15] for r in ins])
        model = {}
        for m in ("pc24", "fp80"):
            o = odir / f"{name}.model_{m}.bin"
            r = sh([str(REFERENCE), m, str(vec_cp), str(o)])
            if r.returncode:
                raise SystemExit(f"reference {m} failed on {name}: {r.stderr}")
            model[m] = read_out(o)
        classes = [classify(native[i], model["pc24"][i][2:], model["fp80"][i][2:]) for i in range(len(ins))]
        disc = [i for i, c in enumerate(classes) if c == "native_equals_pc24_only"]
        fx = {"fixture": entry["fixture"], "sha256": sha(p), "rows": len(ins),
              "distinct_rows": len({tuple(r) for r in ins}),
              "classes": {k: classes.count(k) for k in sorted(set(classes))},
              "discriminating_rows": len(disc), "runs": {}}
        for target, va, vec in (("calc_point", CALC_POINT, vec_cp), ("calc_point_active", CALC_POINT_ACTIVE, vec_ac)):
            for variant in VARIANTS:
                key = f"{target}:{variant}"
                link = build["link"].get(key)
                if not (link and link["ok"]):
                    fx["runs"][key] = {"error": "driver not linked"}
                    continue
                o = odir / f"{name}.{target}.{variant}.bin"
                run = run_binary(Path(ROOT / link["binary"]), vec, o)
                obs = read_out(o) if o.exists() else []
                summary = ET.lifted_summary(obs, native, model["pc24"], model["fp80"], list(range(len(ins))))
                dsum = ET.lifted_summary(obs, native, model["pc24"], model["fp80"], disc)
                first_bad = next((i for i in disc if obs[i][0] != 0 or obs[i][2:] != native[i]), None)
                fx["runs"][key] = {"run": run, "out": rel(o), "out_sha256": sha(o) if o.exists() else None,
                                   "all_rows": summary, "discriminating_rows": dsum,
                                   "first_divergent_discriminating_row": first_bad,
                                   "first_divergent_detail": None if first_bad is None else
                                   {"row": first_bad, "inputs": [f"0x{w:08x}" for w in ins[first_bad]],
                                    "native": [f"0x{w:08x}" for w in native[first_bad]],
                                    "observed": [f"0x{w:08x}" for w in obs[first_bad][2:]],
                                    "status": obs[first_bad][0], "exit_pc": f"0x{obs[first_bad][1]:08x}"}}
                t = totals.setdefault(key, {"rows": 0, "returned": 0, "matches_native": 0,
                                            "discriminating_rows": 0, "discriminating_matches_native": 0})
                t["rows"] += summary["rows"]
                t["returned"] += summary["returned"]
                t["matches_native"] += summary["matches_native"]
                t["discriminating_rows"] += dsum["rows"]
                t["discriminating_matches_native"] += dsum["matches_native"]
        result["fixtures"].append(fx)
    result["totals"] = totals
    return result


def suite_ten(build: dict) -> dict:
    """Re-run the ten spike functions' fixture rows through runtime v0."""
    odir = OUT / "out"
    odir.mkdir(parents=True, exist_ok=True)
    rows_total = matched_ref = matched_spike = 0
    per: list[dict] = []
    for name, va, _callees in TEN:
        vec = SPIKE_VECTORS / f"{name}.bin"
        ref_out = PASS_OUT / f"{name}.pc24.bin"
        spike_out = PASS_OUT / f"{name}.remill.bin"
        e: dict = {"function": f"0x{va:08x}", "name": name, "vectors": rel(vec), "vectors_sha256": sha(vec),
                   "reference_pc24": rel(ref_out), "spike_patched_output": rel(spike_out)}
        ref = read_out(ref_out)
        spike = read_out(spike_out)
        for variant in VARIANTS:
            key = f"{name}:{variant}"
            link = build["link"].get(key)
            if not (link and link["ok"]):
                e[variant] = {"error": "driver not linked"}
                continue
            o = odir / f"ten.{name}.{variant}.bin"
            run = run_binary(Path(ROOT / link["binary"]), vec, o)
            obs = read_out(o) if o.exists() else []
            same_ref = sum(1 for i in range(len(obs)) if obs[i] == ref[i])
            same_spike = sum(1 for i in range(len(obs)) if obs[i] == spike[i])
            first_ref = next((i for i in range(len(obs)) if obs[i] != ref[i]), None)
            first_spike = next((i for i in range(len(obs)) if obs[i] != spike[i]), None)
            e[variant] = {
                "run": run, "out": rel(o), "out_sha256": sha(o) if o.exists() else None,
                "rows": len(obs),
                "returned": sum(1 for r in obs if r[0] == 0),
                "status_counts": {str(s): sum(1 for r in obs if r[0] == s) for s in sorted({r[0] for r in obs})},
                "rows_equal_pc24_reference": same_ref,
                "rows_equal_s1_harness_patched_output": same_spike,
                "first_row_differing_from_reference": first_ref,
                "first_row_differing_from_s1_harness": first_spike,
                "verdict": "EXACT" if same_ref == len(obs) == len(ref) else "DIVERGENT",
            }
            if first_ref is not None:
                e[variant]["first_divergence_detail"] = {
                    "row": first_ref,
                    "observed": [f"0x{w:08x}" for w in obs[first_ref]],
                    "reference": [f"0x{w:08x}" for w in ref[first_ref]],
                    "s1_harness": [f"0x{w:08x}" for w in spike[first_ref]]}
            if variant == "pc24":
                rows_total += len(obs)
                matched_ref += same_ref
                matched_spike += same_spike
        per.append(e)
    return {"per_function": per,
            "totals_pc24": {"functions": len(per), "rows": rows_total,
                            "rows_equal_pc24_reference": matched_ref,
                            "rows_equal_s1_harness_patched_output": matched_spike,
                            "functions_exact": sum(1 for e in per if e.get("pc24", {}).get("verdict") == "EXACT")}}


def declared_intrinsics() -> dict:
    """The __remill_* names the 500-function sample's IR declares."""
    names: set[str] = set()
    for ll in sorted(SAMPLE_LIFT.glob("*.ll")):
        for m in re.finditer(r"^declare[^@\n]*@(__remill_[A-Za-z0-9_]+)", ll.read_text(errors="replace"), re.M):
            names.add(m.group(1))
    return {"source": rel(SAMPLE_LIFT), "files": len(list(SAMPLE_LIFT.glob("*.ll"))), "names": sorted(names)}


def parse_info(text: str) -> dict:
    """The driver's `--info` TSV: the guest layout and the state sizes, measured
    in the built program rather than copied out of a header by hand."""
    kv: dict = {}
    sections: list[dict] = []
    regions: list[dict] = []
    for line in text.strip().splitlines():
        f = line.split("\t")
        if f[0] == "kv":
            kv[f[1]] = f[2]
        elif f[0] == "section":
            sections.append({"name": f[1], "start": f[2], "end": f[3], "raw_bytes": int(f[4]), "permissions": f[5]})
        elif f[0] == "region":
            regions.append({"name": f[1], "start": f[2], "end": f[3], "note": f[4]})
    return {"values": kv, "sections": sections, "regions": regions}


def phase_run(force: bool) -> dict:
    js = OUT / "run.json"
    if js.exists() and not force:
        return load(js)
    build = load(OUT / "build.json")
    any_binary = next((ROOT / e["binary"] for e in build["link"].values() if e["ok"]), None)
    log: dict = {"written": now(), "image": rel(EXE), "image_sha256": sha(EXE)}

    p = sh([str(any_binary), "--intrinsics"])
    rows = [l.split("\t") for l in p.stdout.strip().splitlines()[1:] if l]
    log["intrinsics_implemented_by_runtime"] = [{"name": r[0], "status": r[1], "note": r[2]} for r in rows]
    log["intrinsics_declared_by_sample_ir"] = declared_intrinsics()

    info = sh([str(any_binary), str(EXE), "--info"])
    log["runtime_info"] = parse_info(info.stdout)
    log["runtime_info"]["command"] = cmdline([str(any_binary), str(EXE), "--info"])

    st = sh([str(any_binary), str(EXE), "--selftest"])
    log["selftest"] = {"command": cmdline([str(any_binary), str(EXE), "--selftest"]), "rc": st.returncode,
                       "checks": [{"result": l.split("\t")[0], "check": l.split("\t", 1)[1]}
                                  for l in st.stdout.strip().splitlines()
                                  if "\t" in l and not l.startswith("#") and not l.startswith("selftest\t")],
                       "summary": next((l for l in st.stdout.splitlines() if l.startswith("selftest\t")), ""),
                       "notes": [l[2:] for l in st.stdout.splitlines() if l.startswith("#\t")]}

    log["entry_test_rerun"] = suite_entry_test(build)
    log["ten_function_rerun"] = suite_ten(build)
    dump(js, log)
    return log


