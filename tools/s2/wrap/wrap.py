def tracked_sources() -> list[dict]:
    out = []
    for d in (RUNTIME, HARNESS, HERE):
        for p in sorted(d.iterdir()):
            if p.is_file() and p.suffix in (".c", ".h", ".cpp", ".py"):
                out.append({"path": rel(p), "sha256": sha(p), "lines": p.read_text().count("\n")})
    return out


