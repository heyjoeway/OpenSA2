# ---------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--phase", choices=("lift", "build", "run", "receipt", "all"), default="all")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    order = ("lift", "build", "run", "receipt") if args.phase == "all" else (args.phase,)
    for ph in order:
        if ph == "lift":
            phase_lift(args.force)
        elif ph == "build":
            phase_build(args.force or args.phase == "build")
        elif ph == "run":
            phase_run(args.force or args.phase == "run")
        else:
            phase_receipt()


if __name__ == "__main__":
    main()
