@pytest.fixture(scope="module")
def builds(tmp_path_factory):
    if not ZIG.is_file():
        pytest.fail(f"the pinned zig is not present: {ZIG}")
    d = tmp_path_factory.mktemp("closed-world")
    env = {"PATH": os.defpath, "LC_ALL": "C", "ZIG_LOCAL_CACHE_DIR": str(d / "zc"),
           "ZIG_GLOBAL_CACHE_DIR": os.environ.get(
               "ZIG_GLOBAL_CACHE_DIR", str(ROOT / "private" / "generated" / "zig-cache-tests"))}
    src = D3D9_C.read_text()
    assert src.count(GATE) == 1, "the closed world's gate moved"
    gateless = d / "gateless" / "sa2_d3d9.c"
    gateless.parent.mkdir()
    gateless.write_text(src.replace(GATE, GATE.replace("if (!g_listed[t][slot])", "if (0)")))
    # A header whose Present row is slot 18 (GetBackBuffer's): beside the copy of the
    # device, so its quoted include finds it before -I runtime.
    stale = d / "stale" / "sa2_d3d9.c"
    stale.parent.mkdir()
    stale.write_text(src)
    assert HEADER.read_text().count(PRESENT_ROW) == 1
    (stale.parent / "sa2_d3d9_m7_list.h").write_text(
        HEADER.read_text().replace(PRESENT_ROW, '    { 1,  18, "IDirect3DDevice9", "Present"},'))
    # Present's row dropped by hand and the count fixed up to match, the digest left.
    handedit = d / "handedit" / "sa2_d3d9.c"
    handedit.parent.mkdir()
    handedit.write_text(src)
    (handedit.parent / "sa2_d3d9_m7_list.h").write_text(dropped_row(fix_count=True))
    variants = {"trap": (D3D9_C, []), "open": (D3D9_C, ["-DSA2_D3D9_OPEN_WORLD_UNIT_BUILD"]),
                "gateless": (gateless, []), "stale": (stale, []), "handedit": (handedit, [])}
    out = {}
    for name, (device, flags) in variants.items():
        exe = d / f"probe-{name}"
        done = compile_probe(device, flags, exe, env)
        assert done.returncode == 0, done.stderr
        out[name] = exe
    return d, out, env


def dropped_row(fix_count: bool) -> str:
    """The header with Present's row taken out by hand, its count fixed up or not."""
    text = HEADER.read_text()
    out = text.replace(PRESENT_ROW + "\n", "")
    if fix_count:
        n = listed_n()
        out = out.replace(f"#define SA2_D3D9_M7_LIST_ROWS   {n}u", f"#define SA2_D3D9_M7_LIST_ROWS   {n - 1}u")
    assert out != text and (out.count("SA2_D3D9_M7_LIST_ROWS   ") == 1)
    return out


def compile_probe(device: Path, flags: list[str], exe: Path, env: dict) -> subprocess.CompletedProcess:
    argv = [str(ZIG), "cc", "-target", "x86_64-linux-musl", "-D_GNU_SOURCE", "-O1", "-Wall",
            "-Wextra", "-Werror", *flags, "-I", str(ROOT / "runtime"), str(PROBE), str(device),
            str(ROOT / "runtime" / "sa2_guest_call.c"), "-lm", "-o", str(exe)]
    return subprocess.run(argv, capture_output=True, text=True, env=env)


def probe(builds, variant: str, mode: str, tmp_path: Path, **env_extra) -> tuple[int, dict, str]:
    """(exit code, results, stderr) of one probe run in a minimal environment."""
    _d, exes, _env = builds
    env = {"PATH": os.defpath, "LC_ALL": "C", **env_extra}
    out = tmp_path / f"{variant}-{mode}.json"
    done = subprocess.run([str(exes[variant]), mode, str(out)], capture_output=True, text=True,
                          env=env, timeout=120)
    rec = json.loads(out.read_text()) if out.is_file() else {}
    return done.returncode, rec, done.stderr


def test_the_device_lists_exactly_the_receipts_methods(builds, tmp_path):
    code, rec, _ = probe(builds, "trap", "table", tmp_path)
    assert code == 0 and rec["world_mode"] == "trap"
    listed = {f"{r['interface']}::{r['method']}" for r in rec["table"] if r["listed"]}
    assert listed == device_names()
    rows = header_rows(HEADER.read_text())
    assert rec["listed_count"] == listed_n() == len(rows)
    assert rec["list_digest"] == ML.rows_digest(rows) == rec["closed_world"]["list_digest"]
    # The header's rows, read against the device's own table (the probe's), not the
    # generator's parser: each row's type is that interface's index and its slot the
    # method's slot.
    where = {(r["interface"], r["method"]): (r["type"], r["slot"]) for r in rec["table"]}
    for t, s, i, m in header_rows(HEADER.read_text()):
        assert where[(i, m)] == (t, s), (i, m)


def test_the_mode_comes_from_the_live_keyboard_source(builds, tmp_path):
    fifo = tmp_path / "keys.fifo"
    os.mkfifo(fifo)
    plain = tmp_path / "keys.txt"
    plain.write_text("")
    person = str(tmp_path / "run" / "counts.json")             # play_live, a person
    synthetic = str(tmp_path / "run" / "counts.synthetic.json")  # play_live --synthetic-keys
    live = {"SA2_INPUT_DI_SOURCE": str(fifo)}
    # (variant, environment, mode, live keyboard source, automated session)
    cases = [("trap", {}, "trap", False, False), ("trap", live, "log", True, False),
             ("trap", {**live, "SA2_REC_COUNTS": person}, "log", True, False),
             ("trap", {**live, "SA2_REC_COUNTS": synthetic}, "trap", True, True),
             ("trap", {**live, "SA2_REC_COUNTS": "counts.synthetic.json"}, "trap", True, True),
             ("trap", {**live, "SA2_REC_COUNTS": synthetic + ".x"}, "log", True, False),
             ("trap", {"SA2_REC_COUNTS": synthetic}, "trap", False, True),
             ("trap", {"SA2_INPUT_DI_SOURCE": str(plain)}, "trap", False, False),
             ("trap", {"SA2_INPUT_DI_SOURCE": str(tmp_path / "absent")}, "trap", False, False),
             ("trap", {**live, "SA2_INPUT_DI_SCRIPT": str(plain)}, "trap", False, False),
             ("open", live, "open", True, False), ("open", {}, "open", False, False)]
    for variant, env, want, source, automated in cases:
        code, rec, err = probe(builds, variant, "mode", tmp_path, **env)
        cw = rec["closed_world"]
        assert code == 0 and rec["world_mode"] == want == cw["mode"], (variant, env)
        assert (cw["live_keyboard_source"], cw["automated_session"]) == (source, automated), (variant, env)
        assert err == (summary_none() if want == "log" else ""), (variant, env, err)


def test_the_automated_sessions_marker_is_play_lives():
    """The device tells play_live's automated session (--synthetic-keys) from a person's by
    the recorder's counts file play_live names for it, so the name is held to play_live's
    own command: a rename there fails here instead of putting automated runs in log mode."""
    import play_live as PLV
    src = D3D9_C.read_text()
    m = re.search(r'#define SA2_D3D9_AUTOMATED_COUNTS "([^"]+)"', src)
    assert m, "the device's automated-session marker moved"
    p = PLV.paths(ROOT / "private" / "generated" / "x" / "run")
    got = {}
    for synthetic in (False, True):
        _cmd, spec = PLV.game_command("boot", "b", p, {}, {"build": "b"}, False, False, synthetic)
        env = dict(kv.split("=", 1) for kv in spec.split("|")[1:])
        assert env["SA2_INPUT_DI_SOURCE"].endswith("/input.fifo") and "SA2_INPUT_DI_SCRIPT" not in env
        got[synthetic] = Path(env["SA2_REC_COUNTS"]).name
    assert got == {False: "counts.json", True: m.group(1)} and p["synthetic_counts"].name == m.group(1)


def test_every_unlisted_method_traps_by_name_whatever_its_handler(builds, tmp_path):
    code, rec, err = probe(builds, "trap", "trap", tmp_path)
    assert code == 0 and rec["failures"] == 0, rec.get("failed")
    cw = rec["closed_world"]
    rows = [r for r in cw["unlisted"] if r["method"]]
    # The whole table off the list, m_ok and m_zero among them, each its own row.
    names = {f"{r['interface']}::{r['method']}" for r in rows}
    assert {"IDirect3DDevice9::EvictManagedResources", "IDirect3DDevice9::SetGammaRamp",
            "IDirect3DDevice9::SetCursorProperties", "IDirect3DDevice9::AddRef",
            "IDirect3DDevice9::GetPaletteEntries", "ID3DXConstantTable::AddRef",
            "IDirect3DCubeTexture9::Release"} <= names
    assert not names & device_names()
    assert all(r["outcome"] == "trapped" and r["calls"] == 1 and r["first_caller"] == RETADDR
               and r["first_this"] == DEVICE for r in rows)
    assert cw["unlisted"][-1] == {"interface": "IDirect3DDevice9", "method": None, "slot": 120,
                                  "calls": 1, "first_seq": cw["unlisted"][-1]["first_seq"],
                                  "first_caller": RETADDR, "first_this": DEVICE,
                                  "outcome": "unnamed-slot"}
    assert cw["unlisted_methods"] == len(rows) + 1 == cw["unlisted_calls"]
    assert err == ""
    # The gate removed, the same checks fail: the trap is the gate's, not the probe's.
    code, rec, _ = probe(builds, "gateless", "trap", tmp_path)
    assert code == 1 and {"trap-unlisted", "trap-every-unlisted", "trap-rows"} <= set(rec["failed"])


