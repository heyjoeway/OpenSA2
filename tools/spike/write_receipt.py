#!/usr/bin/env python3
"""Write Documentation/receipts/s1-lifter-spike-v1.json and s1-pc24-check-v1.json
from the spike's generated files.

Sources (all generated by the drivers, none typed here):
  private/generated/spike/functions.json          (Documentation/scripts/s1_spike_extract.py)
  private/generated/spike/<lifter>/results.json   (tools/spike/lift_<lifter>.py)
  private/generated/spike/fixtures/results.json   (tools/spike/fixtures/run_fixtures.py)
  private/lifters/<lifter>.download.json          (tools/spike/install_<lifter>.sh)
  tools/spike/timeline.jsonl via timeline_summary  (minutes; never typed)
Per-lifter x87 counts are grepped from the outputs; the one-line reading of
those counts is the only prose this script carries, and it states what the
counts show. The fixture columns (rows, passed, exact, residue, failed, first
divergent row and field, authority, PC24 verdict) come from the fixture
driver's results, and the design verdict (>= 8/10 adopt, 6-7 pivot base,
else custom emitter) is computed from them on EXACT alone and on
EXACT+RESIDUE-ONLY. The headline S1 score is the pre-patch reading on
EXACT+RESIDUE; the post-pass EXACT count from
Documentation/receipts/s1-remill-pc24-patch-v1.json is carried as
corroboration under its own key, never merged into the headline. Each
lifter's ten-function table carries, next to the verdict, the native-row
count (rows_by_authority.native) and the discriminating-row count (rows
where the PC24 and fp80 reference models differ), with per-lifter totals, so
a reader sees which EXACT verdicts rest on rows that cannot separate the
models. The fixture_runs.limits block lists what the fixture corpus does not
exercise (control word fixed at 0x007F, sqrt served natively, the 0x459260
oracle stub, functions with no x87 arithmetic), each measured from the
generated files or marked reasoned. When the fixture results are absent
every such field says "not attempted" with the reason. No lifted output is
copied: the receipts hold counts, hashes, commands and error heads only.

Usage: .venv/bin/python tools/spike/write_receipt.py
"""
