def pc24_reading(lifter: str, probe: dict) -> str:
    tot = {"rows_where_models_differ": 0, "matches_pc24": 0, "matches_fp80": 0, "neither": 0, "not_run": 0}
    for p in probe.values():
        for k in tot:
            tot[k] += p["summary"][lifter][k]
    n = tot["rows_where_models_differ"]
    if tot["not_run"] == n:
        return f"NOT-RUN on all {n} probe rows"
    if tot["matches_pc24"] == n:
        return f"matches the PC24 reference on all {n} probe rows"
    if tot["matches_fp80"] == n:
        return f"matches the 80-bit model, not PC24, on all {n} probe rows: the lifter computes x87 arithmetic at 64-bit significand and ignores precision control"
    return f"of {n} probe rows: {tot['matches_pc24']} match PC24, {tot['matches_fp80']} match the 80-bit model, {tot['neither']} match neither, {tot['not_run']} not run"


