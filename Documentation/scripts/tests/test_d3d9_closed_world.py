"""The recording device's closed world: the user's ruling of 2026-10-09, item 1.

Every Direct3D method not on the M7 list traps by default in the device, naming the
method and its caller; live play (SA2_INPUT_DI_SOURCE naming a FIFO, in a session that
is not play_live's automated --synthetic-keys one) logs each such method once, counts
every call, answers it as before and reports at exit. The list is
runtime/sa2_d3d9_m7_list.h, generated by tools/s4/m7_device_list.py from the `called`
set of Documentation/receipts/d3d9-methods.json.

Two halves. The generator is held to the receipt and to the device table, and its
--check is shown failing on a stale header, a name the table lacks and a d3dx9 import
off the list. harness/d3d9_closed_world_probe.c drives runtime/sa2_d3d9.c itself, built
five ways: as shipped (trap), as a unit build (open), with the closed world's one gate
removed (gateless: what the trap checks must catch), with a header whose row names
another method (stale: the device must refuse it before the first call), and with a
row dropped by hand and its count fixed up but its digest left (handedit: the device
recomputes the digest and must refuse it too). A header whose count is not its rows
must not compile. No game, no shipped bytes, no recorder.

No count of the list is typed here: it is the receipt's, so a list that grows with a
regenerated header passes unchanged.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "s4"))
import m7_device_list as ML  # noqa: E402
sys.path.insert(0, str(ROOT / "tools" / "s5"))

ZIG = ROOT / "private" / "predecessor-tools" / "zig" / "zig-x86_64-linux-0.15.2" / "zig"
PROBE = ROOT / "harness" / "d3d9_closed_world_probe.c"
D3D9_C = ROOT / "runtime" / "sa2_d3d9.c"
HEADER = ROOT / "runtime" / "sa2_d3d9_m7_list.h"
RECEIPT = ROOT / "Documentation" / "receipts" / "d3d9-methods.json"
GATE = "    if (!g_listed[t][slot]) closed_world(t, slot, row, pc, caller, self, raw + 1);\n"
RETADDR, DEVICE = "0x00401000", "0x03200010"


def called() -> list[str]:
    return json.loads(RECEIPT.read_text())["called"]


def device_names() -> set[str]:
    return {n for n in called() if not n.startswith(ML.D3DX_PREFIX)}


def header_rows(text: str) -> list[tuple[int, int, str, str]]:
    return [(int(t), int(s), i, m) for t, s, i, m in
            re.findall(r'\{\s*(\d+),\s*(\d+), "([A-Za-z0-9]+)", "([A-Za-z0-9]+)"\}', text)]


def listed_n() -> int:
    """The number of device methods on the list, from the receipt."""
    return len(device_names())


def summary_none() -> str:
    return (f"*** d3d9 CLOSED WORLD summary (live play): no method off the M7 list was "
            f"called ({listed_n()} listed, runtime/sa2_d3d9_m7_list.h) ***\n")


PRESENT_ROW = '    { 1,  17, "IDirect3DDevice9", "Present"},'


# ---------------------------------------------------------------- the generator

def test_the_header_is_current_and_is_the_receipts_list():
    assert ML.main(["--check"]) == 0
    text = HEADER.read_text()
    assert text == ML.build()[0]
    rows = header_rows(text)
    assert {f"{i}::{m}" for _t, _s, i, m in rows} == device_names()
    assert len(rows) == listed_n() and f"#define SA2_D3D9_M7_LIST_ROWS   {listed_n()}u\n" in text
    # the digest is the rows' own, over the text the device hashes
    assert ML.rows_text(rows[:2]) == f"{rows[0][0]} {rows[0][1]} {rows[0][2]}::{rows[0][3]}\n" \
        f"{rows[1][0]} {rows[1][1]} {rows[1][2]}::{rows[1][3]}\n"
    assert f'#define SA2_D3D9_M7_LIST_DIGEST "{ML.rows_digest(rows)}"' in text
    # every d3dx9 name is in the comment and nowhere in the rows
    for n in called():
        if n.startswith(ML.D3DX_PREFIX):
            assert f" *   {n}\n" in text


def test_the_output_does_not_depend_on_the_receipts_order(tmp_path):
    doc = json.loads(RECEIPT.read_text())
    doc["called"] = list(reversed(doc["called"]))
    doc["generated_utc"] = "another time"
    r = tmp_path / "receipt.json"
    r.write_text(json.dumps(doc))
    # the header names its source, so the temporary receipt's path is put back
    text = ML.build(receipt=r)[0].replace(ML.rel(r), ML.rel(RECEIPT))
    assert text == HEADER.read_text()


def test_a_listed_name_the_table_lacks_is_refused(tmp_path):
    doc = json.loads(RECEIPT.read_text())
    doc["called"].append("IDirect3DDevice9::NoSuchMethod")
    r = tmp_path / "receipt.json"
    r.write_text(json.dumps(doc))
    with pytest.raises(ML.ListError, match="IDirect3DDevice9::NoSuchMethod: the device table has 0 rows"):
        ML.build(receipt=r)
    assert ML.main(["--check", "--receipt", str(r)]) == 1
    # and a table that renamed a listed method's row
    c = tmp_path / "sa2_d3d9.c"
    src = D3D9_C.read_text()
    assert src.count('"TestCooperativeLevel", m_TestCooperativeLevel}') == 1
    c.write_text(src.replace('"TestCooperativeLevel", m_TestCooperativeLevel}',
                             '"TestCooperativeLevelX", m_TestCooperativeLevel}'))
    assert ML.main(["--check", "--d3d9-c", str(c)]) == 1


def test_a_write_leaves_a_current_header_alone(tmp_path, capsys):
    """link_s4 rebuilds every runtime object when a header's mtime moves, so a write
    that would not change the text does not touch the file."""
    h = tmp_path / "list.h"
    h.write_text(HEADER.read_text())
    os.utime(h, (1_000_000_000, 1_000_000_000))
    assert ML.main(["--header", str(h)]) == 0
    assert h.stat().st_mtime == 1_000_000_000 and h.read_text() == HEADER.read_text()
    assert " is current: " in capsys.readouterr().out
    h.write_text(HEADER.read_text().replace(PRESENT_ROW + "\n", ""))
    assert ML.main(["--header", str(h)]) == 0
    assert h.read_text() == HEADER.read_text() and h.stat().st_mtime != 1_000_000_000


def test_a_stale_header_fails_the_check(tmp_path, capsys):
    h = tmp_path / "list.h"
    text = HEADER.read_text()
    h.write_text(text.replace(PRESENT_ROW + "\n", ""))
    assert ML.main(["--check", "--header", str(h)]) == 1
    assert "is stale against" in capsys.readouterr().err
    assert ML.main(["--check", "--header", str(tmp_path / "missing.h")]) == 1
    doc = json.loads(RECEIPT.read_text())
    doc["called"].append("IDirect3DDevice9::SetFVF")           # a real method, not listed
    r = tmp_path / "receipt.json"
    r.write_text(json.dumps(doc))
    assert ML.main(["--check", "--receipt", str(r)]) == 1


def test_a_d3dx9_import_off_the_list_is_refused(tmp_path):
    src = ML.IMPORTS_C.read_text()
    anchor = '    {"d3dx9_42.dll",  "D3DXFilterTexture",'
    assert src.count(anchor) == 1
    i = tmp_path / "sa2_imports.c"
    i.write_text(src.replace(anchor, '    {"d3dx9_42.dll",  "D3DXCreateFontA", 1, 0, 0},\n' + anchor))
    with pytest.raises(ML.ListError, match="D3DXCreateFontA"):
        ML.build(imports_c=i)
    assert ML.main(["--check", "--imports-c", str(i)]) == 1
    # the answered set is exactly the listed d3dx9 names today
    listed = sorted(n[len(ML.D3DX_PREFIX):] for n in called() if n.startswith(ML.D3DX_PREFIX))
    assert ML.d3dx_stubs(ML.IMPORTS_C) == listed


